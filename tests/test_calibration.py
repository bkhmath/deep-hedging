"""Calibration tests, built on a surface whose answer is known.

The structure of the main test is the only honest way to check an ill-posed inverse
problem: generate a surface from known Heston parameters, fit it, and require the
parameters back. Anything looser ("the residuals are small") can be satisfied by
a fit that has found a different point of a flat valley, which is exactly the failure
mode calibration has.

Everything here runs offline. No test touches the network; the Deribit-specific code
is exercised on a recorded response instead of a live one.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from deephedging import black_scholes as bs
from deephedging import deribit
from deephedging.calibrate import calibrate, synthetic_surface
from deephedging.heston import HestonParams

TRUTH = HestonParams(v0=0.09, kappa=2.0, theta=0.12, xi=0.6, rho=-0.55)


@pytest.fixture(scope="module")
def recovery():
    surface = synthetic_surface(TRUTH)
    return surface, calibrate(surface, n_nodes=128)


def test_the_synthetic_surface_is_arbitrage_free_and_smiles(recovery):
    surface, _ = recovery
    assert len(surface) > 30
    assert surface["market_iv"].between(0.05, 2.0).all()
    # With rho < 0 the smile must slope down in strike at every maturity: that is
    # what a negative spot-variance correlation means.
    for T, slice_ in surface.groupby("maturity"):
        ordered = slice_.sort_values("strike")
        assert ordered["market_iv"].iloc[0] > ordered["market_iv"].iloc[-1], T


def test_the_calibration_recovers_the_generating_parameters(recovery):
    """All five parameters, to three decimal places.

    A noiseless surface generated by the model itself has an exact optimum, and the
    calibration is required to find it over merely get close. The tolerances
    here started out ten times looser and were tightened once the vega filter in
    `calibrate` was in place: before it, four zero-vega quotes were enough to move
    kappa by forty per cent, which is exactly the kind of failure a loose tolerance
    would have hidden.
    """
    _, result = recovery
    fitted = result.params
    assert fitted.v0 == pytest.approx(TRUTH.v0, rel=1e-3)
    assert fitted.rho == pytest.approx(TRUTH.rho, abs=1e-3)
    assert fitted.xi == pytest.approx(TRUTH.xi, rel=1e-3)
    assert fitted.theta == pytest.approx(TRUTH.theta, rel=1e-3)
    assert fitted.kappa == pytest.approx(TRUTH.kappa, rel=5e-3)
    assert fitted.kappa * fitted.theta == pytest.approx(TRUTH.kappa * TRUTH.theta, rel=1e-3)


def test_the_fit_is_tight_in_implied_volatility_space(recovery):
    _, result = recovery
    # A surface generated by the model itself must be fitted to essentially machine
    # precision; anything larger means the optimiser stopped early.
    assert result.rmse_iv < 1e-5, result.rmse_iv
    assert result.max_abs_iv < 1e-4, result.max_abs_iv
    assert result.n_quotes == len(result.fit)


def test_every_starting_point_was_tried_and_they_agree(recovery):
    _, result = recovery
    assert result.starts_tried == 8
    assert result.feller == pytest.approx(TRUTH.feller(), rel=0.01)
    # All eight starts reach the same optimum, which is worth recording: the
    # objective is non-convex and multiple starts are insurance, but on this surface
    # the insurance turns out not to be needed.
    assert result.objective_spread < 1e-12, result.objective_spread


def test_quotes_with_no_vega_would_wreck_the_fit_if_they_were_kept():
    """A regression test for a bug the recovery test caught.

    The objective divides each price residual by the quote's vega to read it as an
    implied-vol residual. A deep out-of-the-money short-dated option has a vega of
    order 1e-11 times the forward, so that division turns a pricing error of 1e-10
    into a residual of order one, and least squares then fits those four quotes in
    preference to the other forty-one. `calibrate` drops them; this test pins the
    consequence of not dropping them, so the filter cannot be removed silently.
    """
    surface = synthetic_surface(TRUTH)
    filtered = calibrate(surface, n_nodes=128)
    unfiltered = calibrate(surface, n_nodes=128, min_vega_fraction=0.0)

    assert filtered.n_dropped == 4
    assert unfiltered.n_dropped == 0
    # The filtered fit recovers kappa; the unfiltered one is out by tens of per cent.
    assert filtered.params.kappa == pytest.approx(TRUTH.kappa, rel=5e-3)
    assert abs(unfiltered.params.kappa / TRUTH.kappa - 1.0) > 0.1
    # And the damage is visible in the reported implied-vol error, which is the
    # quantity a reader of the report would look at.
    assert unfiltered.rmse_iv > 20.0 * filtered.rmse_iv


def test_the_vega_weighted_objective_approximates_the_implied_vol_error():
    # The calibration minimises price residuals divided by the market vega, on the
    # grounds that this is the implied-vol residual to first order. Check the
    # approximation directly: perturb a volatility, and compare the price change
    # divided by vega against the volatility change.
    S, K, T, sigma = 100.0, 110.0, 0.5, 0.4
    vega = float(bs.call_vega(S, K, T, 0.0, 0.0, sigma))
    for h in [1e-3, 1e-4]:
        price_change = float(bs.call_price(S, K, T, 0.0, 0.0, sigma + h)) - float(
            bs.call_price(S, K, T, 0.0, 0.0, sigma)
        )
        assert price_change / vega == pytest.approx(h, rel=0.01)


def test_enforcing_feller_cannot_improve_the_fit():
    # Adding a constraint can only make the attainable objective worse or leave it
    # unchanged. Stated on a surface whose truth violates the condition, so the
    # constraint binds.
    violating = HestonParams(v0=0.10, kappa=1.0, theta=0.10, xi=0.9, rho=-0.6)
    assert violating.feller() < 0
    surface = synthetic_surface(violating)
    free = calibrate(surface, n_nodes=96, enforce_feller=False)
    constrained = calibrate(surface, n_nodes=96, enforce_feller=True)
    assert constrained.rmse_iv >= free.rmse_iv - 1e-9
    # And the constraint must actually have moved the parameters towards satisfying
    # it, otherwise the penalty is not doing anything.
    assert free.params.feller() < constrained.params.feller() + 1e-6


def _fake_snapshot() -> pd.DataFrame:
    """A recorded-shape Deribit response, so the cleaning logic is tested offline."""
    now_ms = 1_700_000_000_000
    day = 24 * 3600 * 1000
    rows = []
    for days, expiry in [(10, now_ms + 10 * day), (60, now_ms + 60 * day)]:
        for strike in [40_000, 60_000, 84_000, 110_000, 200_000]:
            for option_type in ["call", "put"]:
                rows.append(
                    {
                        "instrument_name": f"BTC-{days}d-{strike}-{option_type[0].upper()}",
                        "strike": float(strike),
                        "option_type": option_type,
                        "expiration_timestamp": expiry,
                        "mark_price": 0.05,
                        "mark_iv": 55.0,
                        "underlying_price": 84_000.0,
                        "bid_price": 0.04,
                        "ask_price": 0.06,
                        "open_interest": 10.0,
                        "volume": 1.0,
                        "snapshot_ms": now_ms,
                    }
                )
    # Two rows that must be filtered out: a stale one-sided quote and a far wing.
    rows.append({**rows[0], "instrument_name": "BTC-stale", "bid_price": 0.0})
    rows.append({**rows[0], "instrument_name": "BTC-wing", "strike": 5_000.0})
    return pd.DataFrame(rows)


def test_clean_surface_keeps_out_of_the_money_quotes_and_drops_the_rest():
    clean = deribit.clean_surface(_fake_snapshot())
    assert len(clean) > 0
    # Exactly one contract per (strike, maturity): puts below the forward, calls above.
    assert not clean.duplicated(subset=["strike", "maturity"]).any()
    below = clean[clean["moneyness"] < 1.0]
    above = clean[clean["moneyness"] >= 1.0]
    assert (below["option_type"] == "put").all()
    assert (above["option_type"] == "call").all()
    # The venue quotes implied vol in percent and the code must convert it.
    assert clean["market_iv"].between(0.5, 0.6).all()
    # Maturities in years, and the wing and the one-sided quote are gone.
    assert clean["maturity"].between(5 / 365, 200 / 365).all()
    assert "BTC-stale" not in set(clean["instrument_name"])
    assert "BTC-wing" not in set(clean["instrument_name"])
    # Moneyness inside the kept band.
    assert clean["moneyness"].between(0.6, 1.6).all()


def test_clean_surface_computes_a_relative_spread_for_weighting():
    clean = deribit.clean_surface(_fake_snapshot())
    # (0.06 - 0.04) / 0.05 = 0.4
    assert np.allclose(clean["rel_spread"], 0.4)


def test_loading_without_a_cache_says_what_to_do(tmp_path, monkeypatch):
    monkeypatch.setattr(deribit, "CACHE_DIR", tmp_path)
    with pytest.raises(FileNotFoundError, match="download_surface"):
        deribit.load_surface()


def test_a_snapshot_round_trips_through_the_cache(tmp_path):
    snapshot = _fake_snapshot()
    path = deribit.save_surface(snapshot, tmp_path / "surface.parquet")
    reloaded = deribit.load_surface(path)
    assert len(reloaded) == len(snapshot)
    assert set(reloaded.columns) == set(snapshot.columns)
